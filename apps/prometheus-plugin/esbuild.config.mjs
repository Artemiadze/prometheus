import esbuild from "esbuild";
import { copyFileSync, existsSync, mkdirSync } from "node:fs";
import { builtinModules } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const isWatch = process.argv.includes("watch");
const isProduction = !isWatch;

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
prometheus-plugin
*/
`;

/**
 * Optional path to an Obsidian Vault used for local plugin development.
 * Example: TEST_VAULT=/path/to/Vault/.obsidian/plugins/prometheus
 * When unset, the build still succeeds and only skips the copy step.
 */
function resolveTestVaultPluginDir() {
  const fromEnv = process.env.TEST_VAULT?.trim();
  if (fromEnv) {
    return resolve(fromEnv);
  }
  return null;
}

function copyArtifacts() {
  const target = resolveTestVaultPluginDir();
  if (target === null) {
    if (isWatch) {
      console.warn(
        "[prometheus-plugin] TEST_VAULT is unset; skipping copy into a local Vault.",
      );
    }
    return;
  }
  mkdirSync(target, { recursive: true });
  for (const file of ["main.js", "manifest.json", "styles.css"]) {
    const source = join(root, file);
    if (!existsSync(source)) {
      continue;
    }
    copyFileSync(source, join(target, file));
  }
  console.log(`[prometheus-plugin] copied artifacts to ${target}`);
}

/** @type {import("esbuild").BuildOptions} */
const buildOptions = {
  banner: { js: banner },
  entryPoints: [join(root, "src/bootstrap/main.ts")],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/state",
    "@codemirror/view",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2020",
  platform: "node",
  logLevel: "info",
  sourcemap: isProduction ? false : "inline",
  treeShaking: true,
  outfile: join(root, "main.js"),
  minify: isProduction,
};

async function main() {
  if (isWatch) {
    const context = await esbuild.context({
      ...buildOptions,
      plugins: [
        {
          name: "copy-to-vault",
          setup(build) {
            build.onEnd((result) => {
              if (result.errors.length === 0) {
                copyArtifacts();
              }
            });
          },
        },
      ],
    });
    await context.watch();
    console.log("[prometheus-plugin] watching for changes…");
    return;
  }

  await esbuild.build(buildOptions);
  copyArtifacts();
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
